#!/bin/bash
set -e

# build_app.sh - Compiles FastView and bundles it into a standalone macOS FastView.app

APP_NAME="FastView"
BUNDLE_NAME="${APP_NAME}.app"
CONTENTS_DIR="${BUNDLE_NAME}/Contents"
MACOS_DIR="${CONTENTS_DIR}/MacOS"
RESOURCES_DIR="${CONTENTS_DIR}/Resources"
CONFIGURATION="${1:-release}"

echo "==> Building FastView in ${CONFIGURATION} mode..."
swift build -c "${CONFIGURATION}"

BIN_DIR=$(swift build -c "${CONFIGURATION}" --show-bin-path)

echo "==> Creating macOS App Bundle layout at ${BUNDLE_NAME}..."
rm -rf "${BUNDLE_NAME}"
mkdir -p "${MACOS_DIR}"
mkdir -p "${RESOURCES_DIR}"

# Copy binary
cp "${BIN_DIR}/${APP_NAME}" "${MACOS_DIR}/${APP_NAME}"
chmod +x "${MACOS_DIR}/${APP_NAME}"

# Copy resource bundle(s) if generated by SPM
if [ -d "${BIN_DIR}/${APP_NAME}_${APP_NAME}.bundle" ]; then
    cp -R "${BIN_DIR}/${APP_NAME}_${APP_NAME}.bundle" "${RESOURCES_DIR}/"
fi
if [ -f "Sources/FastView/Resources/AppIcon.png" ]; then
    cp "Sources/FastView/Resources/AppIcon.png" "${RESOURCES_DIR}/"
fi

# Generate AppIcon.icns from AppIcon.png if sips and iconutil are present
if command -v sips >/dev/null 2>&1 && command -v iconutil >/dev/null 2>&1; then
    echo "==> Generating AppIcon.icns..."
    ICONSET_DIR=$(mktemp -d)/AppIcon.iconset
    mkdir -p "${ICONSET_DIR}"
    SRC_ICON="Sources/FastView/Resources/AppIcon.png"

    sips -z 16 16     "${SRC_ICON}" --out "${ICONSET_DIR}/icon_16x16.png" >/dev/null 2>&1 || true
    sips -z 32 32     "${SRC_ICON}" --out "${ICONSET_DIR}/icon_16x16@2x.png" >/dev/null 2>&1 || true
    sips -z 32 32     "${SRC_ICON}" --out "${ICONSET_DIR}/icon_32x32.png" >/dev/null 2>&1 || true
    sips -z 64 64     "${SRC_ICON}" --out "${ICONSET_DIR}/icon_32x32@2x.png" >/dev/null 2>&1 || true
    sips -z 128 128   "${SRC_ICON}" --out "${ICONSET_DIR}/icon_128x128.png" >/dev/null 2>&1 || true
    sips -z 256 256   "${SRC_ICON}" --out "${ICONSET_DIR}/icon_128x128@2x.png" >/dev/null 2>&1 || true
    sips -z 256 256   "${SRC_ICON}" --out "${ICONSET_DIR}/icon_256x256.png" >/dev/null 2>&1 || true
    sips -z 512 512   "${SRC_ICON}" --out "${ICONSET_DIR}/icon_256x256@2x.png" >/dev/null 2>&1 || true
    sips -z 512 512   "${SRC_ICON}" --out "${ICONSET_DIR}/icon_512x512.png" >/dev/null 2>&1 || true
    sips -z 1024 1024 "${SRC_ICON}" --out "${ICONSET_DIR}/icon_512x512@2x.png" >/dev/null 2>&1 || true

    iconutil -c icns "${ICONSET_DIR}" -o "${RESOURCES_DIR}/AppIcon.icns" >/dev/null 2>&1 || true
    rm -rf "$(dirname "${ICONSET_DIR}")"
fi

# Create Info.plist
cat << 'EOF' > "${CONTENTS_DIR}/Info.plist"
<?xml version="1.0" encoding="UTF-8"?>
<!DOCTYPE plist PUBLIC "-//Apple//DTD PLIST 1.0//EN" "http://www.apple.com/DTDs/PropertyList-1.0.dtd">
<plist version="1.0">
<dict>
    <key>CFBundleDevelopmentRegion</key>
    <string>en</string>
    <key>CFBundleExecutable</key>
    <string>FastView</string>
    <key>CFBundleIconFile</key>
    <string>AppIcon</string>
    <key>CFBundleIdentifier</key>
    <string>com.fastview.app</string>
    <key>CFBundleInfoDictionaryVersion</key>
    <string>6.0</string>
    <key>CFBundleName</key>
    <string>FastView</string>
    <key>CFBundlePackageType</key>
    <string>APPL</string>
    <key>CFBundleShortVersionString</key>
    <string>1.0</string>
    <key>CFBundleVersion</key>
    <string>1</string>
    <key>LSMinimumSystemVersion</key>
    <string>12.0</string>
    <key>NSHighResolutionCapable</key>
    <true/>
    <key>NSPrincipalClass</key>
    <string>NSApplication</string>
</dict>
</plist>
EOF

echo "==> Successfully created ${BUNDLE_NAME}!"
